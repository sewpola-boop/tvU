import assert from 'node:assert/strict';
import {build} from 'esbuild';
const result=await build({entryPoints:['lib/benefits.ts'],bundle:true,write:false,platform:'node',format:'esm'});
const {matchBenefits,benefitTotals}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const base={age:30,seoul:true};
const ids=p=>matchBenefits(p).map(x=>x.id);
assert.deepEqual(ids(base),[]);
assert.equal(ids({...base,employment:'seeking',income:''}).includes('youth'),false);
const youth=matchBenefits({...base,employment:'seeking',income:'100',housing:'rent',newlywed:'yes'});
assert.ok(youth.find(x=>x.id==='youth').closed);assert.equal(youth.filter(x=>x.id==='youth-rent').length,1);
assert.equal(benefitTotals(youth).monthly,0);assert.ok(youth.some(x=>x.period==='대출한도'));
assert.equal(ids({...base,seoul:false,income:'100',employment:'seeking',housing:'rent',newlywed:'yes'}).length,0);
const parent=matchBenefits({...base,child:'0',care:'home'});assert.equal(parent.find(x=>x.id==='parent').amount,1000000);assert.equal(ids({...base,child:'0',care:'home'}).includes('care'),false);assert.equal(benefitTotals(parent).monthly,1000000);
assert.equal(ids({...base,child:'preschool',care:'institution'}).includes('care'),false);
assert.equal(ids({...base,child:'preschool',care:'home'}).includes('care'),true);
assert.equal(ids({...base,disability:'severe',sensitiveConsent:false}).includes('disability-pension'),false);
assert.ok(ids({...base,disability:'severe',sensitiveConsent:true}).includes('disability-pension'));
assert.equal(ids({...base,age:65,disability:'severe',sensitiveConsent:true}).includes('disability-pension'),false);
assert.equal(matchBenefits({...base,age:65,disability:'severe',sensitiveConsent:true}).filter(x=>x.id==='learning').length,1);
assert.equal(ids({...base,child:'elementary',income:'100'}).includes('education'),false);
assert.equal(matchBenefits({...base,child:'high',income:'50'}).find(x=>x.id==='education').amount,860000);
assert.equal(benefitTotals(matchBenefits({...base,birth:'postpartum',order:'3'})).monthly,0);
assert.equal(ids({...base,age:40,employment:'seeking',income:'100'}).includes('youth'),false);
assert.equal(ids({...base,age:18,employment:'seeking',income:'100'}).includes('youth'),false);
console.log('PASS: unknown input, Seoul boundaries, age thresholds, closed recruitment, childcare exclusivity, disability consent, pension age, duplicate vouchers, income, noncash/loan total exclusion');
